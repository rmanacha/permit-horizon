"""The committed web bundle (web/public/results/, decision 74) must match the current code and register.

The bundle is regenerated by hand (`make results-all export`) because building it needs the full
data download; this test makes a stale bundle fail CI instead of shipping silently.

Two checks (decision 75): the register fingerprint in meta.json equals parameters.yaml now, and
no file the bundle depends on (WATCHED below) changed between the commit recorded in
meta.json (``git_shas``) and HEAD. The second needs git history: CI checks out with
``fetch-depth: 0``; in a source archive or a shallow clone the test skips and says why.
"""

import hashlib
import json
import subprocess
from pathlib import Path

import pytest

from hre.assumptions.loader import PARAMETERS_PATH
from hre.model.run import RESULTS_SCHEMA_VERSION

REPO = Path(__file__).resolve().parents[1]
BUNDLE = REPO / "web" / "public" / "results"
# Everything that decides a number in the bundle and lives in git (decision 75, plus the CLI,
# whose _run_one assembles meta, rounds and loads the current-law files: decision 78).
WATCHED = ("src/hre/model/", "src/hre/assumptions/", "src/hre/current_law/", "src/hre/schema.py",
           "src/hre/export.py", "src/hre/cli.py")


@pytest.fixture(scope="module")
def meta():
    p = BUNDLE / "meta.json"
    if not p.exists():
        pytest.skip("no committed bundle yet")
    return json.loads(p.read_text(encoding="utf-8"))


def test_bundle_was_built_from_the_current_register(meta):
    now = hashlib.sha256(PARAMETERS_PATH.read_bytes()).hexdigest()
    assert meta["parameters_sha256"] == now, (
        "web/public/results/ was built from an older parameters.yaml; run 'make results-all export' and commit")


def test_bundle_schema_and_completeness(meta):
    assert meta["results_schema_version"] == RESULTS_SCHEMA_VERSION
    index = json.loads((BUNDLE / "index.json").read_text(encoding="utf-8"))
    states = {r["state"] for r in index["states"]}
    assert len(states) == meta["jurisdictions"] == 51
    assert all((BUNDLE / f"{s}.json").exists() for s in states)
    assert not any(m.endswith("-dirty") for m in meta["git_shas"]), "export from a clean checkout"


def _git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(REPO), *args], check=False, capture_output=True, text=True)


def test_bundle_was_built_from_the_current_engine(meta):
    try:
        inside = _git("rev-parse", "--is-inside-work-tree")
    except OSError:
        pytest.skip("git is not installed, so the engine-change check cannot run here (CI runs it)")
    if inside.returncode != 0:
        pytest.skip("not a git checkout (a source archive?), so the engine-change check cannot run here")
    shallow = _git("rev-parse", "--is-shallow-repository").stdout.strip() == "true"
    for recorded in meta["git_shas"]:
        sha = recorded.removesuffix("-dirty")
        if _git("cat-file", "-e", f"{sha}^{{commit}}").returncode != 0:
            if shallow:
                pytest.skip(f"commit {sha[:7]} from meta.json is not in this shallow clone; "
                            "fetch full history (CI uses fetch-depth: 0) to run the engine-change check")
            pytest.fail(f"commit {sha[:7]} recorded in web/public/results/meta.json is not in this "
                        "repository's history; regenerate the bundle from a pushed commit")
        diff = _git("diff", "--name-only", sha, "HEAD", "--", *WATCHED)
        assert diff.returncode == 0, diff.stderr
        changed = diff.stdout.split()
        assert not changed, (
            f"web/public/results/ was built at {sha[:7]}, and these files changed since: "
            f"{', '.join(changed[:8])}{' ...' if len(changed) > 8 else ''}. Commit the code, run "
            "'make results-all export' from the clean checkout, and commit the bundle on its own.")


def _sentences(obj):
    if isinstance(obj, dict):
        for v in obj.values():
            yield from _sentences(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _sentences(v)
    elif isinstance(obj, str) and obj.count(" ") >= 3:
        yield obj


def test_text_the_website_shows_has_no_internal_references():
    """Sentences in the bundle reach legislators verbatim: no decision numbers, phase names or ids."""
    import re

    bad = re.compile(r"\bdecisions? \d|\bPhase \d|\b(net_permits|stock_change|cost_response_proxy|completed_homes|"
                     r"alternative_band|newly_affected_share)\b")
    files = sorted(BUNDLE.glob("[A-Z][A-Z].json")) + [BUNDLE / "registers.json"]
    hits = []
    for f in files:
        data = json.loads(f.read_text(encoding="utf-8"))
        if f.name == "registers.json":     # current-law notes are kept for reviewers and never shown
            for law in data["current_law"].values():
                for sc in law["scenarios"].values():
                    sc.pop("notes", None)
            data.pop("validation_ledger", None)   # checked by tests/test_ledger.py
        hits += [f"{f.name}: {m.group(0)!r} in {s[:90]!r}" for s in _sentences(data) if (m := bad.search(s))]
    assert not hits, hits[:10]
