"""The committed web bundle (web/public/results/, decision 74) must match the current code and register.

The bundle is regenerated by hand (`make results-all export`) because building it needs the full
data download; this test makes a stale bundle fail CI instead of shipping silently.
"""

import hashlib
import json
from pathlib import Path

import pytest

from hre.assumptions.loader import PARAMETERS_PATH
from hre.model.run import RESULTS_SCHEMA_VERSION

BUNDLE = Path(__file__).resolve().parents[1] / "web" / "public" / "results"


@pytest.fixture(scope="module")
def meta():
    p = BUNDLE / "meta.json"
    if not p.exists():
        pytest.skip("no committed bundle yet")
    return json.loads(p.read_text(encoding="utf-8"))


def test_bundle_was_built_from_the_current_register(meta):
    now = hashlib.sha256(PARAMETERS_PATH.read_bytes()).hexdigest()
    assert meta["parameters_sha256"] == now, (
        "web/public/results/ was built from an older parameters.yaml; run 'make results-all export' and commit")


def test_bundle_schema_and_completeness(meta):
    assert meta["results_schema_version"] == RESULTS_SCHEMA_VERSION
    index = json.loads((BUNDLE / "index.json").read_text(encoding="utf-8"))
    states = {r["state"] for r in index["states"]}
    assert len(states) == meta["jurisdictions"] == 51
    assert all((BUNDLE / f"{s}.json").exists() for s in states)
    assert not any(m.endswith("-dirty") for m in meta["git_shas"]), "export from a clean checkout"
