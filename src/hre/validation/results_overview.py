"""Sanity review of the all-state results (Phase 3 step 10): docs/evidence/results_overview.md.

Reads every results/{ST}.json and writes the tables; the observations under the marker
are written by hand and kept when the tables are regenerated.

Outlier rule: a state's default increment, as a percent of its baseline, more than three
times or less than a third of the median across states. Scenarios whose median is below
0.1% of baseline (TOD) are not flagged this way: the ratio test is meaningless near zero, and
their zero-exposure states are counted in the distribution table instead.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path
from typing import Any

from hre.data.states import lookup

SCENARIOS = ("adu", "missing_middle", "tod", "parking", "fees")
MIN_MEDIAN_PCT = 0.1
MARKER = "<!-- observations below are written by hand; hre validate --overview keeps them -->"
# Adam Ruege's v2.0 New Hampshire results (research/boss_version_review.md section 4)
ADAM_NH = {"adu": (700, 2000, 4700, "completed homes"), "missing_middle": (0, 1600, 3800, "net permits"),
           "tod": (0, 0, 0, "stock change (3.7 and 42 unrounded)"), "parking": (0, 100, 400, "cost-response proxy"),
           "fees": (0, 800, 3200, "cost-response proxy")}


def load(results_dir: Path) -> list[dict[str, Any]]:
    out = []
    for p in sorted(results_dir.glob("*.json")):
        if not (p.stem.isalpha() and p.stem.isupper()) or lookup(p.stem).synthetic:
            continue
        out.append(json.loads(p.read_text(encoding="utf-8")))
    return out


def rows(results: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out = []
    for r in results:
        b = r["baseline"]["state"]["mid"]
        row = {"state": r["meta"]["state"], "baseline": b,
               "stock": (r["cross_check"]["housing_units_pep"]["state"] or {}).get("end")}
        for s in SCENARIOS:
            sc = r["scenarios"][s]
            row[s] = {"benchmark": sc["benchmark"]["mid"], "outcome": sc["benchmark"]["outcome"],
                      "increment": sc["increment"]["estimate"]["mid"],
                      "high": sc["increment"]["estimate"]["high"],
                      "share": sc["increment"]["newly_affected_share"],
                      "pct": 100 * sc["increment"]["estimate"]["mid"] / b if b else 0.0}
        row["combined"] = r["combined"]["increment"]["estimate"]
        row["combined_pct"] = 100 * row["combined"]["mid"] / b if b else 0.0
        out.append(row)
    return out


def outliers(rs: list[dict[str, Any]]) -> list[str]:
    flags = []
    for s in SCENARIOS:
        pcts = [r[s]["pct"] for r in rs]
        med = statistics.median(pcts)
        if med < MIN_MEDIAN_PCT:
            continue
        for r in rs:
            p = r[s]["pct"]
            if p > 3 * med or p < med / 3:
                flags.append(f"{s}: {r['state']} {p:.2f}% of baseline (median {med:.2f}%)")
    return flags


def _f(x: float) -> str:
    return f"{x:,.0f}"


def render(results: list[dict[str, Any]], run_date: str, keep: str = "") -> str:
    rs = rows(results)
    L = [
        "# Results overview: every jurisdiction, every scenario, and a sanity review",
        "",
        (f"Generated by `hre validate --overview` on {run_date} from {len(rs)} results files "
         "(`hre run --all`). Mid assumption set unless a column says otherwise; increments are the "
         "register default (newly affected share from current law) in permits. Code: "
         "`src/hre/validation/results_overview.py`."),
        "",
        "## 1. Every jurisdiction (mid)",
        "",
        "| State | Baseline permits | ADU | Missing middle | TOD | Parking | Fees | Combined | Combined % of baseline |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rs:
        L.append(f"| {r['state']} | {_f(r['baseline'])} | "
                 + " | ".join(f"{_f(r[s]['increment'])} ({r[s]['pct']:.1f}%)" for s in SCENARIOS)
                 + f" | {_f(r['combined']['mid'])} | {r['combined_pct']:.1f}% |")
    tot = {s: sum(r[s]["increment"] for r in rs) for s in SCENARIOS}
    base = sum(r["baseline"] for r in rs)
    combined = sum(r["combined"]["mid"] for r in rs)
    L += ["", (f"All {len(rs)} together: baseline {_f(base)} permits; increments "
               + ", ".join(f"{s} {_f(tot[s])} ({100 * tot[s] / base:.1f}%)" for s in SCENARIOS)
               + f"; combined {_f(combined)}."), ""]
    L += ["## 2. Distribution across states (increment as % of baseline, mid)", "",
          "| Scenario | Min | Median | Max | States with zero |", "|---|---|---|---|---|"]
    for s in SCENARIOS:
        p = sorted(r[s]["pct"] for r in rs)
        zero = sum(1 for r in rs if r[s]["increment"] == 0)
        lo_st = min(rs, key=lambda r: r[s]["pct"])["state"]
        hi_st = max(rs, key=lambda r: r[s]["pct"])["state"]
        L.append(f"| {s} | {p[0]:.2f}% ({lo_st}) | {statistics.median(p):.2f}% | {p[-1]:.2f}% ({hi_st}) | {zero} |")
    fl = outliers(rs)
    L += ["", (f"Outlier flags (more than 3x or under 1/3 of the median; scenarios with a median under "
               f"{MIN_MEDIAN_PCT}% of baseline are not flagged): {len(fl)}."), ""]
    L += [f"- {f}" for f in fl] or ["- none"]
    L += ["", "## 3. Orders of magnitude against the literature", ""]
    ca = next((r for r in rs if r["state"] == "CA"), None)
    if ca:
        L.append(f"- **California ADUs.** Our CA benchmark is {_f(ca['adu']['benchmark'])} completed ADUs over five "
                 f"years, {_f(ca['adu']['benchmark'] / 5)} a year; California completed about 17,500 to 22,500 "
                 "a year in 2023-2025 (de-duplicated HCD) and permitted 30,000 to 40,000. The tier rates are "
                 "fitted on California, so this is a consistency check, not a test.")
    worst = max(rs, key=lambda r: (r["missing_middle"]["high"] + r["tod"]["high"]) / r["stock"] if r["stock"] else 0)
    L.append(f"- **National scale.** All five together add {_f(combined)} permits at mid over five years, "
             f"{100 * combined / base:.1f}% of the {_f(base)}-permit national baseline.")
    if worst["stock"]:
        share = 100 * (worst["missing_middle"]["high"] + worst["tod"]["high"]) / worst["stock"]
        L.append(f"- **Upzoning upper bound.** Auckland's upzoning added 4.1% of its stock in five years. Our "
                 f"largest missing middle plus TOD high case relative to the housing stock is {worst['state']}, "
                 f"{share:.2f}% of its stock: below Auckland, as a single-state reform with a narrower scope should be.")
    nh = next((r for r in rs if r["state"] == "NH"), None)
    if nh:
        L += ["", "## 4. New Hampshire against Adam Ruege's v2.0", "",
              "| Scenario | Adam low / mid / high | Ours: benchmark mid (unit) | Ours: increment low / mid / high (permits) |",
              "|---|---|---|---|"]
        r = next(x for x in results if x["meta"]["state"] == "NH")
        for s in SCENARIOS:
            a = ADAM_NH[s]
            sc = r["scenarios"][s]
            e = sc["increment"]["estimate"]
            b = sc["benchmark"]
            L.append(f"| {s} | {_f(a[0])} / {_f(a[1])} / {_f(a[2])} ({a[3]}) | {_f(b['mid'])} ({b['outcome']}; "
                     f"{_f(b['low'])} to {_f(b['high'])}) | {_f(e['low'])} / {_f(e['mid'])} / {_f(e['high'])} |")
    L += ["", MARKER, ""]
    return "\n".join(L) + (keep if keep else "")


def write(results_dir: Path, dest: Path, run_date: str) -> int:
    results = load(results_dir)
    if not results:
        raise FileNotFoundError(f"no results files in {results_dir}; run 'hre run --all' first")
    keep = ""
    if dest.exists():
        text = dest.read_text(encoding="utf-8")
        if MARKER in text:
            keep = text.split(MARKER, 1)[1].lstrip("\n")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(render(results, run_date, keep), encoding="utf-8")
    return len(results)
